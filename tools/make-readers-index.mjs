#!/usr/bin/env node
/**
 * Generate `readers/tests.js`, the registry of reading-system tests.
 *
 * The results page needs to know about every test, including tests that nobody
 * has run yet, and it needs the title, assertion and specification link that
 * are already stored in each book. Deriving the registry from the package and
 * content documents keeps those values in one place.
 *
 * Usage:
 *   node tools/make-readers-index.mjs          # write readers/tests.js
 *   node tools/make-readers-index.mjs --check  # fail if it is out of date
 *
 * @license [W3C Software and Document License](https://www.w3.org/Consortium/Legal/copyright-software)
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { listTests } from './make-epubs.mjs'

/** Repository root, derived from this file's location. */
const rootDir = join(dirname(fileURLToPath(import.meta.url)), '..')

/** Directory holding one subdirectory per reading-system test. */
const readersDir = join(rootDir, 'readers')

/** Generated registry consumed by `results/readers.html`. */
const registryFile = join(readersDir, 'tests.js')

/**
 * Decode the handful of XML entities used in the book metadata.
 *
 * @param {string} value Text from an XML document.
 * @returns {string} Decoded text.
 */
function decode (value) {
	return value
		.replace(/&lt;/g, '<')
		.replace(/&gt;/g, '>')
		.replace(/&quot;/g, '"')
		.replace(/&#39;|&apos;/g, "'")
		.replace(/&amp;/g, '&')
	}

/**
 * Extract one required value from an XML document.
 *
 * @param {string} xml Document text.
 * @param {RegExp} pattern Pattern whose first capture group is the value.
 * @param {string} what Human-readable name of the missing value.
 * @param {string} file File the value should have come from.
 * @returns {string} Trimmed, decoded value.
 */
function readValue (xml, pattern, what, file) {
	const match = pattern.exec(xml)
	if (! match) throw new Error(`Cannot find ${what} in ${file}`)
	return decode(match[1].trim())
	}

/**
 * Read the metadata for one test from its package and content documents.
 *
 * @param {string} name Test directory name.
 * @returns {{id: string, identifier: string, title: string, assert: string, help: string, modified: string, languages: string[]}} Test metadata.
 */
function readTest (name) {
	const packageFile = join(readersDir, name, 'EPUB', 'package.opf')
	const contentFile = join(readersDir, name, 'EPUB', 'content_001.xhtml')
	const packageXml = readFileSync(packageFile, 'utf8')
	const contentXml = readFileSync(contentFile, 'utf8')

	const identifier = readValue(packageXml, /<dc:identifier[^>]*>([\s\S]*?)<\/dc:identifier>/, 'dc:identifier', packageFile)
	if (! identifier.endsWith(`/${name}/`) && identifier !== name) {
		throw new Error(`dc:identifier in readers/${name}/EPUB/package.opf should end with /${name}/`)
		}
	const languages = [...packageXml.matchAll(/<dc:language[^>]*>([\s\S]*?)<\/dc:language>/g)]
		.map((match) => decode(match[1].trim()))
		.filter(Boolean)

	return {
		id: name,
		identifier,
		title: readValue(packageXml, /<dc:title>([\s\S]*?)<\/dc:title>/, 'dc:title', packageFile),
		assert: readValue(contentXml, /<meta\s+name="assert"\s+content="([^"]*)"/, 'meta name="assert"', contentFile),
		help: readValue(contentXml, /<link\s+rel="help"\s+href="([^"]*)"/, 'link rel="help"', contentFile),
		modified: readValue(packageXml, /<meta\s+property="dcterms:modified">([\s\S]*?)<\/meta>/, 'dcterms:modified', packageFile),
		languages
		}
	}

/**
 * Build the registry from the test directories.
 *
 * @returns {object[]} Test metadata, sorted by identifier.
 */
export function buildRegistry () {
	return listTests()
		.map(readTest)
		.sort((a, b) => a.id.localeCompare(b.id))
	}

/**
 * Render the registry as a browser-loadable JavaScript file.
 *
 * @param {object[]} tests Test metadata.
 * @returns {string} File contents.
 */
export function renderRegistry (tests) {
	return `/*
	Generated by tools/make-readers-index.mjs from each readers/<test>/EPUB/package.opf.
	Do not edit this file by hand.
*/
var readertests = ${JSON.stringify(tests, null, '\t')}
`
	}

/** Write the registry, or check that the existing file is current. */
function main () {
	const check = process.argv.includes('--check')
	const output = renderRegistry(buildRegistry())
	if (check) {
		const current = existsSync(registryFile) ? readFileSync(registryFile, 'utf8') : ''
		if (current !== output) {
			console.error('readers/tests.js is out of date; run node tools/make-readers-index.mjs')
			process.exitCode = 1
			}
		return
		}
	writeFileSync(registryFile, output)
	console.log(registryFile)
	}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
	main()
	}
